	<header class="mb-16">
		<h2 class="font-mono text-muted">[ 01 SIGNAL ]</h2>
	</header>

	<div class="font-xl font-medium space-y-8">
		<p>
			Most companies building complex technology can explain what they do. Fewer can make anyone feel why it matters. The explanation is fluent — the team is credible, the market is real. But somewhere between what's been built and what the world believes, the signal breaks down.
		</p>

		<p>
			The usual response is to hire a brand agency. Compress everything into a tagline. Redesign the website. Shoot a launch film. It helps for a month. Then the same problem returns — because the problem was never the surface. It was the structure underneath.
		</p>

		<p>
			When the investor narrative says one thing, the customer story says another, and the careers page says a third, that's not a communications problem. It's a coherence problem. No amount of polish fixes architecture. The tagline doesn't hold because there's nothing underneath it to hold.
		</p>

		<p>
			What's missing is narrative architecture — the structural logic underneath how a company explains itself. Not a deck. Not a brand book no one opens after launch week. A north-star artifact that strategy is built into, not bolted onto. Something a team can actually scale from.
		</p>
	</div>
</section>
